export function importFieldsForType(type: DataImportType): ImportFieldDefinition[] {
  if (type === "animals") return ANIMAL_IMPORT_FIELDS
  if (type === "treatments") return TREATMENT_IMPORT_FIELDS
  return GRAZING_IMPORT_FIELDS
}

export function importTypeLabel(type: DataImportType): string {
  if (type === "animals") return "Animals"
  if (type === "treatments") return "Treatment records"
  return "Grazing history"
}
